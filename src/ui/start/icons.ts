export const FALLBACK: Icon = Box;

export function iconFor(name: string | undefined): Icon {
  const icon = name ? ICONS[name.trim().toLowerCase()] : undefined;
  if (name && !icon) console.warn(`[icons] no icon '${name}' in src/ui/start/icons.ts, using fallback`);
  return icon ?? FALLBACK;
}
